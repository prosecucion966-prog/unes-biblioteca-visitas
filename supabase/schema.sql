create extension if not exists pgcrypto;
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '',
 role text not null default 'operator' check(role in ('admin','operator')),
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.visitas (
 id bigint generated by default as identity primary key,
 cedula text not null, apellidos text not null, nombres text not null,
 genero text not null default '', tipo_visitante text not null,
 categoria_estudio text not null default '', programa_detalle text not null default '',
 nucleo text not null default '', telefono text not null default '', correo text not null default '',
 fecha_visita date not null default (now() at time zone 'America/Caracas')::date,
 hora_entrada time not null default (now() at time zone 'America/Caracas')::time,
 hora_salida time, area_consulta text not null, tipo_actividad text not null default '',
 numero_maquina text not null default '', procedencia text not null default '',
 atendido_por text not null default '', material_consultado text not null default '',
 created_by uuid references auth.users(id), created_at timestamptz not null default now(),
 constraint visita_checkout_after_check check(hora_salida is null or hora_salida >= hora_entrada)
);
create index if not exists visitas_fecha_idx on public.visitas(fecha_visita desc);
create index if not exists visitas_cedula_idx on public.visitas(cedula);
create or replace function public.current_app_active() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active=true);
$$;
create or replace function public.current_app_role() returns text language sql stable security definer set search_path='' as $$
 select p.role from public.profiles p where p.id=(select auth.uid()) and p.active=true limit 1;
$$;
alter table public.profiles enable row level security;
alter table public.visitas enable row level security;
drop policy if exists profiles_read_self_or_admin on public.profiles;
create policy profiles_read_self_or_admin on public.profiles for select to authenticated using(id=(select auth.uid()) or (select public.current_app_role())='admin');
drop policy if exists profiles_admin_manage on public.profiles;
create policy profiles_admin_manage on public.profiles for all to authenticated using((select public.current_app_role())='admin') with check((select public.current_app_role())='admin');
drop policy if exists visitas_read_active on public.visitas;
create policy visitas_read_active on public.visitas for select to authenticated using((select public.current_app_active()));
drop policy if exists visitas_insert_active on public.visitas;
create policy visitas_insert_active on public.visitas for insert to authenticated with check((select public.current_app_active()) and (created_by is null or created_by=(select auth.uid())));
drop policy if exists visitas_delete_admin on public.visitas;
create policy visitas_delete_admin on public.visitas for delete to authenticated using((select public.current_app_role())='admin');
create or replace function public.registrar_salida_visita(p_visit_id bigint) returns table(id bigint,hora_salida time) language plpgsql security definer set search_path='' as $$
declare v_salida time;
begin
 if not coalesce(public.current_app_active(),false) then raise exception 'No autorizado'; end if;
 update public.visitas v set hora_salida=(now() at time zone 'America/Caracas')::time where v.id=p_visit_id and v.hora_salida is null returning v.hora_salida into v_salida;
 if not found then raise exception 'La visita no existe o ya tiene salida'; end if;
 return query select p_visit_id,v_salida;
end; $$;
revoke all on function public.registrar_salida_visita(bigint) from public;
grant execute on function public.registrar_salida_visita(bigint) to authenticated;
grant usage on schema public to authenticated;
grant select on public.profiles,public.visitas to authenticated;
grant insert,delete on public.visitas to authenticated;
grant execute on function public.current_app_active() to authenticated;
grant execute on function public.current_app_role() to authenticated;
